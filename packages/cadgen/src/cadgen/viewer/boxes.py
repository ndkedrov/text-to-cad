"""Box builder for the CAD Viewer: save a box, build its parts in bounded child processes.

Where boxes live
    A local viewer keeps them in ``<root>/boxes/<name>/``. A hosted viewer (one
    that serves several signed-in accounts) gives each account its own
    ``<root>/boxes/u-<hash of its e-mail>/<name>/``; no route reaches another
    account's folder. A box folder holds ``<name>.box.json`` (the editable
    description), a generated model script per part (``<name>_base.py``,
    ``<name>_lid.py``) and the ``.step``/``.stl``/``.3mf`` those scripts build.

What is trusted
    Nothing the client sends is executed. The geometry arrives as a plan in
    ``cadgen.box_plan``'s grammar, is checked against it, and is written into the
    scripts as a literal. Each script then runs as ``python <script>`` in a child
    process -- never inside this server, which does not load the kernel -- with a
    wall-clock timeout that kills the whole process tree, CPU-time and file-size
    limits, and output captured to a size-limited file. At most ``max_builds`` run
    at once behind a bounded queue.

What a hosted viewer adds
    One active build per account, per-account daily counts of new boxes and
    builds, a daily cap on new boxes across all accounts, a disk budget per
    account, a refusal to start builds when the disk runs low, and a throwaway
    cadgen cache per build so nothing accumulates outside the box folders.
"""

